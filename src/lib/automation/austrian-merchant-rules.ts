function reviewedExisting(
  id: string,
  category: ReviewedBookingMerchant["category"],
  requiresCategoryEvidence = false,
): ReviewedBookingMerchant {
  const identity = expandedMerchantIdentities.find(
    (merchant) => merchant.id === id,
  );
  if (!identity)
    throw new Error(`Missing existing public merchant identity: ${id}`);
  return {
    id,
    canonicalName: identity.canonicalName,
    aliases: [],
    wikidataId: identity.wikidataId,
    category,
    requiresCategoryEvidence,
    evidenceUrl: `https://www.wikidata.org/wiki/${identity.wikidataId}`,
  };
}

